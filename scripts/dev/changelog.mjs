// Writes src/content/changelog.ts (the public /changelog page) from the merged items of
// docs/PROGRAM-STATUS.md. Only items with a public wording in PUBLIC below appear: owner-only, workspace,
// security and automation items never reach the public page, and the wording never comes from the status
// file itself. The date of each item is the date of its merge commit on main.
//
//   node scripts/dev/changelog.mjs           write src/content/changelog.ts
//   node scripts/dev/changelog.mjs --check   exit 1 if it is out of date
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");

/** Item id in docs/PROGRAM-STATUS.md → what visitors are told. Add a line when a public item merges. */
export const PUBLIC = {
  "0.2": "One address, houcine.world, for every page link, the sitemap and robots.txt.",
  "0.4": "Every page is checked before release: titles, headings, links, images and accessibility.",
  "0.4b": "Clearer forms and buttons for screen readers, better heading order and contrast.",
  "0.5": "Pages load faster: each page downloads only the code it needs.",
  B1: "The brand page: the design language of the site, with copy-ready values.",
  B3b: "A content layer for projects, journal posts and questions, checked before it is published.",
  B4: "Work and Journal pages, with an RSS feed.",
  B5: "The ecosystem map, and questions and answers about the ecosystem.",
  B6: "Site search: press Ctrl+K or / on any page.",
  Q1: "A Skip to content link and clearer keyboard focus on every page.",
  Q2: "Lighter pages: images load as you scroll, and less code is downloaded.",
  Q3: "Every page fits phone screens, with larger tap targets on touch screens.",
  Q4: "Better previews when a page is shared.",
  Q5: "A clear message, with a reload button, when a page cannot load.",
  C1: "The Team page.",
  C2: "The Services page: what each vertical does and who it is for.",
  C3: "The brand kit: download the logo and the share image.",
  C5: "The Status page: which version of the site you are seeing.",
  C6: "This changelog.",
};

const status = readFileSync(join(root, "docs/PROGRAM-STATUS.md"), "utf8");
const merged = [...status.matchAll(/^\| ([^|]+?) \|.*\*\*Merged\*\* \(#(\d+)/gm)].map((m) => ({ id: m[1].trim(), pr: Number(m[2]) }));
const log = execFileSync("git", ["log", "origin/main", "--format=%cs %s", "-300"], { cwd: root, encoding: "utf8" });
const dateOf = (pr) => log.split("\n").find((l) => l.endsWith(`(#${pr})`))?.slice(0, 10) ?? null;

const entries = merged
  .filter((m) => Object.hasOwn(PUBLIC, m.id))
  .map((m) => ({ date: dateOf(m.pr), text: PUBLIC[m.id] }))
  .filter((e) => e.date)
  .sort((a, b) => (a.date < b.date ? 1 : a.date > b.date ? -1 : 0));

const file = `// GENERATED by scripts/dev/changelog.mjs from docs/PROGRAM-STATUS.md: do not edit by hand.
// Only items with a public wording in that script appear here.

export interface ChangelogEntry {
  /** Merge date, YYYY-MM-DD. */
  date: string;
  text: string;
}

export const changelog: ChangelogEntry[] = ${JSON.stringify(entries, null, 2).replace(/"(date|text)":/g, "$1:")};
`;

const target = join(root, "src/content/changelog.ts");
if (process.argv.includes("--check")) {
  const same = readFileSync(target, "utf8") === file;
  console.log(same ? "src/content/changelog.ts: up to date" : "src/content/changelog.ts: OUT OF DATE");
  process.exit(same ? 0 : 1);
}
writeFileSync(target, file);
console.log(`src/content/changelog.ts: written (${entries.length} entries)`);
